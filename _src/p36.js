function gearPath(cx, cy, R, z, ph) {
  const ad = 7, dd = 7, p = 360 / z; let d = '';
  for (let k = 0; k < z; k++) {
    const c = ph + k * p;
    [[R - dd, c - 0.5 * p], [R - dd, c - 0.27 * p], [R + ad, c - 0.15 * p], [R + ad, c + 0.15 * p], [R - dd, c + 0.27 * p]].forEach(([r, a], i) => {
      const [x, y] = pol(cx, cy, r, a); d += (k === 0 && i === 0 ? 'M' : 'L') + f(x) + ',' + f(y) + ' ';
    });
  }
  return d + 'Z';
}
function gearBody(cx, cy, R, z, ph) {
  let s = `<path d="${gearPath(cx, cy, R, z, ph)}" class="body"/>`;
  for (let k = 0; k < 5; k++) { const [x, y] = pol(cx, cy, R * 0.56, k * 72 + 18); s += `<circle cx="${f(x)}" cy="${f(y)}" r="${f(R * 0.15)}" class="hole"/>`; }
  return s + `<circle cx="${cx}" cy="${cy}" r="17" class="body"/>`;
}
