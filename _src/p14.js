// 桁架图：nodes 名→坐标，bars [编号, 端点1, 端点2, 编号偏移]，zero {编号: 第几步变零}
function trussSvg(c) {
  let s = '';
  s += c.supports || '';
  c.bars.forEach(([no, p, q, off]) => {
    const P = c.nodes[p], Q = c.nodes[q], k = c.zero[no];
    s += D.bar(P, Q, k != null ? { u: k } : {});
    if (k != null) s += D.bar(P, Q, { cls: 'zero', s: k });
    if (no) {
      const mx = (P[0] + Q[0]) / 2 + (off ? off[0] : 0), my = (P[1] + Q[1]) / 2 + (off ? off[1] : 0);
      s += `<text x="${f(mx)}" y="${f(my + 5)}" class="mn" text-anchor="middle">${no}</text>`;
      if (k != null) s += `<text x="${f(mx)}" y="${f(my + 24)}" class="zl" text-anchor="middle"${at({ s: k })}>零杆</text>`;
    }
  });
  Object.values(c.nodes).forEach(P => s += D.pin(P[0], P[1], { r: 4.5 }));
  (c.focus || []).forEach(([n, k]) => { const P = c.nodes[n]; s += `<circle cx="${P[0]}" cy="${P[1]}" r="17" class="focus"${at({ s: k, u: k + 1 })}/>`; });
  s += c.loads || '';
  s += c.labels || '';
  return s;
}
