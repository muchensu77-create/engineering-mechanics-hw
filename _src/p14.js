// c: sup [{x,t:'pin'|'roll'|'wallL'|'wallR'}], q [[x1,x2]], F [x], M [{x,cw}], lab [[x,y,text]], dims, fbd (第1步待求力), qres (第1步合力), res (结果)
function beamSvg(c) {
  let s = '';
  (c.dims || []).forEach(d => s += D.dim(d[0], 335, d[1], 335, d[2], { off: 18 }));
  (c.q || []).forEach(q => s += D.q(q[0], q[1], BY - 6));
  s += D.rod([[c.x1, BY], [c.x2, BY]]);
  (c.sup || []).forEach(p => {
    if (p.t === 'pin') s += D.fixed(p.x, BY, 0, { dk: 1 });
    else if (p.t === 'roll') s += D.roller(p.x, BY, 0, { dk: 1 });
    else s += D.wall(p.x, BY - 52, BY + 52, p.t === 'wallL' ? 1 : -1, { dk: 1 });
  });
  (c.F || []).forEach(x => s += D.ai(x, BY - 6, 64, 270, { g: 0, l: 'F', lp: [x + 15, BY - 52] }));
  (c.M || []).forEach(m => s += D.couple(m.x, BY, 22, m.cw, 'M', { lp: [m.x + (m.dx || 0), BY - 36] }));
  (c.lab || []).forEach(L => s += D.txt(L[0], L[1], L[2]));
  s += D.g((c.qres || []).map(r => D.ai(r[0], BY - 6, 72, 270, { c: 'g', dash: 1, g: 0, l: r[1], lp: [r[0] + 6, BY - 86], la: 'start' })).join(''), { s: 1 });
  s += c.fbd || '';
  s += c.res || '';
  return s;
}
